"use client";

import {
  useCallback,
  useEffect,
  useId,
  useLayoutEffect,
  useRef,
  useSyncExternalStore,
} from "react";
import { createPortal } from "react-dom";
import { Info } from "lucide-react";
import { cn } from "@/utils/cn";

const TIP_TEXT = "Answers are prepared in advance, not generated by AI.";
const VIEWPORT_CLEARANCE = 12;
const MAX_TIP_WIDTH = 240;
const TIP_GAP = 6;

type ChatbotInfoTipProps = {
  open: boolean;
  onOpenChange: (open: boolean) => void;
};

function subscribeNoop() {
  return () => {};
}

function resolveTipBox(
  trigger: DOMRect,
  tipHeight: number,
  panel: DOMRect | null,
) {
  const width = Math.min(
    MAX_TIP_WIDTH,
    Math.max(0, window.innerWidth - VIEWPORT_CLEARANCE * 2),
  );

  // Start under the trigger, then pull inward so the tip stays in-viewport
  // (and preferably over the chat panel) instead of hanging off the right edge.
  let left = trigger.left;

  if (panel) {
    const panelInset = 8;
    const panelMaxLeft = panel.right - panelInset - width;
    if (left > panelMaxLeft) {
      left = Math.max(panel.left + panelInset, panelMaxLeft);
    }
  }

  const maxLeft = window.innerWidth - VIEWPORT_CLEARANCE - width;
  if (left > maxLeft) left = Math.max(VIEWPORT_CLEARANCE, maxLeft);
  if (left < VIEWPORT_CLEARANCE) left = VIEWPORT_CLEARANCE;

  let top = trigger.bottom + TIP_GAP;
  const height = tipHeight > 0 ? tipHeight : 48;
  const maxTop = window.innerHeight - VIEWPORT_CLEARANCE - height;
  if (top > maxTop) top = Math.max(VIEWPORT_CLEARANCE, maxTop);

  return { top, left, width };
}

export function ChatbotInfoTip({ open, onOpenChange }: ChatbotInfoTipProps) {
  const tipId = useId();
  const triggerRef = useRef<HTMLButtonElement>(null);
  const tipRef = useRef<HTMLDivElement>(null);
  const closeTimerRef = useRef<number | null>(null);
  const mounted = useSyncExternalStore(subscribeNoop, () => true, () => false);

  const clearCloseTimer = useCallback(() => {
    if (closeTimerRef.current !== null) {
      window.clearTimeout(closeTimerRef.current);
      closeTimerRef.current = null;
    }
  }, []);

  const updatePosition = useCallback(() => {
    const trigger = triggerRef.current;
    const tip = tipRef.current;
    if (!trigger || !tip) return;

    const panel = document.querySelector("[data-chatbot-panel]");
    const { top, left, width } = resolveTipBox(
      trigger.getBoundingClientRect(),
      tip.offsetHeight,
      panel?.getBoundingClientRect() ?? null,
    );

    tip.style.top = `${top}px`;
    tip.style.left = `${left}px`;
    tip.style.width = `${width}px`;
    tip.style.visibility = "visible";
  }, []);

  useLayoutEffect(() => {
    if (!open) return;
    updatePosition();
    const frame = window.requestAnimationFrame(() => updatePosition());
    return () => window.cancelAnimationFrame(frame);
  }, [open, updatePosition]);

  useEffect(() => {
    if (!open) return;

    const onReposition = () => updatePosition();
    window.addEventListener("resize", onReposition);
    window.addEventListener("scroll", onReposition, true);

    return () => {
      window.removeEventListener("resize", onReposition);
      window.removeEventListener("scroll", onReposition, true);
    };
  }, [open, updatePosition]);

  useEffect(() => {
    if (!open) return;

    function onKeyDown(event: KeyboardEvent) {
      if (event.key !== "Escape") return;
      event.preventDefault();
      event.stopImmediatePropagation();
      onOpenChange(false);
      triggerRef.current?.focus();
    }

    window.addEventListener("keydown", onKeyDown, true);
    return () => window.removeEventListener("keydown", onKeyDown, true);
  }, [open, onOpenChange]);

  useEffect(() => {
    if (!open) return;

    function onPointerDown(event: MouseEvent | TouchEvent) {
      const target = event.target as Node | null;
      if (!target) return;
      if (triggerRef.current?.contains(target)) return;
      if (tipRef.current?.contains(target)) return;
      onOpenChange(false);
    }

    document.addEventListener("mousedown", onPointerDown);
    document.addEventListener("touchstart", onPointerDown);
    return () => {
      document.removeEventListener("mousedown", onPointerDown);
      document.removeEventListener("touchstart", onPointerDown);
    };
  }, [open, onOpenChange]);

  useEffect(() => () => clearCloseTimer(), [clearCloseTimer]);

  function scheduleClose() {
    clearCloseTimer();
    closeTimerRef.current = window.setTimeout(() => {
      if (triggerRef.current === document.activeElement) return;
      onOpenChange(false);
    }, 120);
  }

  function openTip() {
    clearCloseTimer();
    onOpenChange(true);
  }

  const tipNode =
    mounted && open
      ? createPortal(
          <div
            ref={tipRef}
            id={tipId}
            role="tooltip"
            data-chatbot-info-tip
            style={{
              position: "fixed",
              top: 0,
              left: 0,
              maxWidth: MAX_TIP_WIDTH,
              visibility: "hidden",
              // Above [data-floating-actions] (z-50); portal escapes overflow clipping.
              zIndex: 60,
            }}
            onMouseEnter={openTip}
            onMouseLeave={scheduleClose}
            className={cn(
              "rounded-lg border border-border bg-surface px-2.5 py-2 text-left text-[12px] leading-snug text-pretty break-words text-foreground shadow-lg",
              "pointer-events-auto",
            )}
          >
            {TIP_TEXT}
          </div>,
          document.body,
        )
      : null;

  return (
    <>
      <button
        ref={triggerRef}
        type="button"
        aria-expanded={open}
        aria-controls={tipId}
        aria-describedby={open ? tipId : undefined}
        onClick={() => onOpenChange(!open)}
        onPointerEnter={(event) => {
          if (event.pointerType === "mouse") openTip();
        }}
        onPointerLeave={(event) => {
          if (event.pointerType === "mouse") scheduleClose();
        }}
        onFocus={openTip}
        onBlur={(event) => {
          const next = event.relatedTarget as Node | null;
          if (next && tipRef.current?.contains(next)) return;
          scheduleClose();
        }}
        className="inline-flex size-7 items-center justify-center rounded-md text-muted transition hover:bg-surface-muted hover:text-foreground focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
        aria-label="About HelpNova Assistant answers"
      >
        <Info className="size-3.5" aria-hidden />
      </button>
      {tipNode}
    </>
  );
}
