function svgForIcon(inner: string, color: string, strokeWidth: number) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
}

/** Preload the 12 integration icons as images tinted for the current ribbon theme. */
export async function loadRibbonIntegrationIcons(
  color: string,
  strokeWidth = 2.05,
): Promise<HTMLImageElement[]> {
  return Promise.all(
    ribbonIntegrationIds.map(async (id) => {
      const inner = iconInnerById[id];
      if (!inner) {
        throw new Error(`Missing ribbon icon markup for ${id}`);
      }
      const src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(
        svgForIcon(inner, color, strokeWidth),
      )}`;
      const img = new Image();
      img.decoding = "async";
      img.src = src;
      await img.decode();
      return img;
    }),
  );
}
